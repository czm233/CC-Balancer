import { activationGuard, simulate, time } from './planner'
import type { Settings } from './planner'

export function scriptPrompt(s: Settings, timezone: string) {
  const guard = activationGuard(s.first)
  const starts = simulate(s, s.first).cycles.map(c => time(c.start))
  return `请帮我配置一个简单的定时 API 调用任务，用于按我的计划尝试开启 Coding Plan 的 5 小时额度窗口。

【定时计划】
计划时区：${timezone}（请向我确认，并按此时区配置，不直接依赖服务器默认时区）
首次触发时间：${time(s.first)}
每个执行日的全部触发时间：${starts.join('、')}
以上时间已包含首次触发，每个节点只发送一次请求，不要重复添加首次任务，也不要设置成全天无限每隔 5 小时执行。
执行日期：请询问我是每天、工作日还是指定日期执行。

【先向我确认】
1. 使用什么定时工具和运行环境，例如 Clockwork、cron，或 Python 配合系统定时任务；优先使用我已有的工具，不强制编写 Python。
2. API 地址、模型、请求格式及认证方式，并确认这个接口使用的是我的 Coding Plan 额度。
3. 计划时区及执行日期。
凭证通过环境变量或工具的安全配置提供，不要写入源码或日志。

【任务只需做这些】
- 在每个指定时间点，发送一次最小 AI 请求，请求内容固定为“say OK”。
- 设置合理的请求超时，记录调用时间及请求成功或失败，不记录密钥和敏感响应内容。
- 无论请求成功、失败或超时，都不自动重试、不补跑、不改变后续触发时间。下一个节点照常执行。
- 不检测已有额度窗口，不等待窗口结束，不处理其他人使用造成的偏差，也不负责确认或修复窗口开启状态。
- 首次安装或重启不立即补发请求，只等待下一个计划节点。避免重复安装相同定时任务。

【我的使用前提】
我会自行安排 ${guard.startLabel}–${guard.endLabel} 暂停使用，以配合首次触发。这是给我的提醒，不需要脚本执行或监控。
请求成功只代表调用成功，不代表新窗口一定开启；窗口是否开启由服务端决定，不属于此脚本的职责。

确认信息后，请给出最简单可用的定时配置或脚本、占位配置示例、启用及停用方法，以及不发送真实请求的时间表检查方法。不要增加窗口监控、自动恢复或复杂调度逻辑。`
}
